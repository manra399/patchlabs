/* PatchLabs free AI model shutdown check (/tools/model-shutdown-check). Runs only in the browser: no network, no storage.
   Reads pasted code, .env, JSON or YAML and finds every OpenAI model id and API feature that OpenAI has shut down or
   scheduled for shutdown, with the date, days left and OpenAI's named replacement. The table comes from OpenAI's
   deprecations page (model-shutdowns.js, generated by tools/gen/openai_shutdowns.py). Also loads under Node for tests. */
(function (root) {
  'use strict';
  var D = root.PLModelShutdowns || (typeof require === 'function' ? require('./model-shutdowns.js') : null);
  var RANK = { critical: 0, high: 1, medium: 2, low: 3 };
  var DAY = 86400000;

  // API features with their own shutdown dates (OpenAI's 'Feature and endpoint deprecations' and past tables).
  var FEATURES = [
    { key: 'assistants', re: /\bbeta\s*\.\s*(assistants|threads)\b|\/v1\/(assistants|threads)\b|assistants\s*=\s*v[12]\b/, name: 'Assistants API', shutdown: '2026-08-26', replacement: 'the Responses API and Conversations API' },
    { key: 'realtime-v1', re: /OpenAI-Beta['"]?\s*[:,]\s*['"]?realtime=v1/, name: 'Realtime beta header (realtime=v1)', shutdown: '2026-05-12', replacement: 'the GA Realtime API (no beta header)' },
    { key: 'prompts', re: /\/v1\/prompts\b|\bpmpt_[A-Za-z0-9]{6,}/, name: 'Reusable prompt objects (/v1/prompts)', shutdown: '2026-11-30', replacement: 'prompt text kept in your own code' },
    { key: 'agent-builder', re: /\bwf_[a-f0-9]{16,}|\bworkflow_id\s*[:=]\s*['"]wf_/, name: 'Agent Builder workflow', shutdown: '2026-11-30', replacement: 'the Agents SDK or ChatGPT Workspace Agents' },
    { key: 'translations', re: /\/v1\/audio\/translations\b|\baudio\s*\.\s*translations\b/, name: 'Audio translations endpoint', shutdown: '2027-02-26', replacement: '/v1/realtime/translations' }
  ];

  function iso(d) { return d.toISOString().slice(0, 10); }
  function daysBetween(a, b) { return Math.round((Date.parse(b + 'T00:00:00Z') - Date.parse(a + 'T00:00:00Z')) / DAY); }
  function severity(days) { return days <= 0 ? 'critical' : days <= 90 ? 'high' : days <= 180 ? 'medium' : 'low'; }
  function fmt(isoDate) {
    var m = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    var p = isoDate.split('-');
    return (+p[2]) + ' ' + m[+p[1] - 1] + ' ' + p[0];
  }
  function escRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

  var BY_ID = {}, ALT;
  (D ? D.models : []).forEach(function (m) { BY_ID[m.id] = m; });
  // Longest ids first so gpt-4o-mini-tts wins over gpt-4o-mini and gpt-4o.
  ALT = Object.keys(BY_ID).sort(function (a, b) { return b.length - a.length; }).map(escRe).join('|');
  var MODEL_RE = ALT ? new RegExp('(^|[^\\w.\\-/])(' + ALT + ')(?![\\w.\\-])', 'g') : null;
  var OPENAI_ID = /(^|[^\w.\-/])((?:gpt-[\d.]+(?:-[a-z][\w.\-]*)?|o\d(?:-[a-z][\w\-]*)?|chatgpt-[\w.\-]+|gpt-image-[\w.\-]+|gpt-realtime[\w.\-]*|gpt-audio[\w.\-]*|whisper-1|tts-1(?:-hd)?|dall-e-[23]|text-embedding-[\w\-]+))(?![\w.\-])/g;

  function scan(text, today) {
    var src = String(text || '');
    if (!src.trim()) return { error: 'Paste your code, .env or config first.' };
    if (src.length > 2000000) return { error: 'That is more than 2 MB. Paste the files that call the AI API.' };
    today = today || iso(new Date());
    var lines = src.split('\n');
    var hits = {}, order = [], current = {};
    var shortOk = function (line, idx, id) {
      // Bare o1/o3/o4-mini style ids are short words; only count them inside quotes or after model= / model:.
      if (!/^o\d/.test(id)) return true;
      var before = line.slice(Math.max(0, idx - 12), idx);
      return /['"`]$/.test(before) || /model\w*\s*[=:]\s*$/i.test(before);
    };
    lines.forEach(function (line, i) {
      if (MODEL_RE) {
        MODEL_RE.lastIndex = 0;
        var m;
        while ((m = MODEL_RE.exec(line))) {
          var id = m[2], at = m.index + m[1].length;
          if (!shortOk(line, at, id)) continue;
          if (!hits[id]) { hits[id] = { id: id, lines: [] }; order.push(id); }
          if (hits[id].lines.indexOf(i + 1) < 0) hits[id].lines.push(i + 1);
        }
      }
      OPENAI_ID.lastIndex = 0;
      var o;
      while ((o = OPENAI_ID.exec(line))) {
        var cid = o[2], cat = o.index + o[1].length;
        if (BY_ID[cid] || !shortOk(line, cat, cid)) continue;
        if (!current[cid]) current[cid] = i + 1;
      }
    });

    var findings = order.map(function (id) {
      var m = BY_ID[id], h = hits[id], days = daysBetween(today, m.shutdown);
      return {
        kind: 'model', id: id, line: h.lines[0], lines: h.lines, code: lines[h.lines[0] - 1].trim().slice(0, 220),
        shutdown: m.shutdown, days: days, severity: severity(days), replacement: m.replacement, alias: !!m.alias,
        title: days <= 0 ? id + ' was shut down on ' + fmt(m.shutdown) : id + ' shuts down on ' + fmt(m.shutdown),
        detail: (days <= 0 ? 'OpenAI’s API no longer serves this model, so these calls return an error now. '
          : days + ' day' + (days === 1 ? '' : 's') + ' left. After that date the call returns an error instead of a reply. ') +
          (m.alias ? 'OpenAI’s table lists the dated snapshots behind this name, not the name itself, and doesn’t say what the bare name will do; plan as if it stops too. ' : '') +
          'OpenAI’s named replacement: ' + m.replacement + '.'
      };
    });
    FEATURES.forEach(function (f) {
      for (var i = 0; i < lines.length; i++) {
        if (!f.re.test(lines[i])) continue;
        var days = daysBetween(today, f.shutdown);
        findings.push({
          kind: 'feature', id: f.name, line: i + 1, lines: [i + 1], code: lines[i].trim().slice(0, 220), shutdown: f.shutdown, days: days,
          severity: severity(days), replacement: f.replacement, alias: false,
          title: f.name + (days <= 0 ? ' was shut down on ' : ' shuts down on ') + fmt(f.shutdown),
          detail: (days <= 0 ? 'OpenAI has already switched this off, so this code fails now. ' : days + ' day' + (days === 1 ? '' : 's') + ' left. ') + 'Replacement: ' + f.replacement + '.'
        });
        break;
      }
    });
    findings.sort(function (a, b) { return RANK[a.severity] - RANK[b.severity] || a.days - b.days || a.line - b.line; });
    var passed = Object.keys(current).map(function (id) { return { id: id, line: current[id], label: id + ': no shutdown announced' }; })
      .sort(function (a, b) { return a.line - b.line; });
    return { lines: lines.length, today: today, fetched: D ? D.fetched : '', findings: findings, passed: passed };
  }

  function prompt(r) {
    var out = ['OpenAI is shutting down models and API features this app uses. Update each one below to the replacement named, keep the',
      'same behaviour, and make the model name a single setting (one constant or env var) so the next change is one line.', ''];
    r.findings.forEach(function (f) {
      out.push('- ' + f.id + ' (line' + (f.lines.length > 1 ? 's ' + f.lines.join(', ') : ' ' + f.line) + '): ' +
        (f.days <= 0 ? 'already shut down on ' : 'shuts down on ') + fmt(f.shutdown) + '. Replace with ' + f.replacement + '.');
    });
    out.push('', 'Then run the app’s main AI features once each and compare the replies with the old model before deploying.',
      'If the new model needs different parameters (reasoning settings, max_completion_tokens instead of max_tokens), change those too.');
    return out.join('\n');
  }

  function sample() {
    return [
      '// lib/ai.ts',
      "import OpenAI from 'openai';",
      'const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });',
      '',
      'export async function summarise(text: string) {',
      '  const r = await openai.chat.completions.create({',
      "    model: 'gpt-4o',",
      "    messages: [{ role: 'user', content: text }],",
      '  });',
      '  return r.choices[0].message.content;',
      '}',
      '',
      'export async function speak(text: string) {',
      "  return openai.audio.speech.create({ model: 'gpt-4o-mini-tts', voice: 'alloy', input: text });",
      '}',
      '',
      'export async function tutor(question: string) {',
      '  const thread = await openai.beta.threads.create();',
      "  return openai.beta.threads.runs.create(thread.id, { assistant_id: 'asst_123' });",
      '}',
      '',
      '# .env',
      'OPENAI_MODEL=gpt-4.1-mini',
      'OPENAI_REASONING_MODEL=o3',
      'OPENAI_NEW_MODEL=gpt-6-luna'
    ].join('\n');
  }

  var API = { scan: scan, prompt: prompt, sample: sample, fmt: fmt, data: D };
  if (typeof module === 'object' && module.exports) module.exports = API; else root.PLModelCheck = API;
})(this);

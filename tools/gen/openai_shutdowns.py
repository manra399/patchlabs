#!/usr/bin/env python3
"""Builds site/static/assets/model-shutdowns.js from OpenAI's deprecations page (the Markdown version).

    python3 tools/gen/openai_shutdowns.py            # fetch https://developers.openai.com/api/docs/deprecations.md
    python3 tools/gen/openai_shutdowns.py FILE.md    # or read a saved copy

Every backticked model id in the 'Upcoming deprecations' and 'Past deprecations' tables becomes a row
{id, shutdown (YYYY-MM-DD), replacement, upcoming}. Rows from before 2025 are dropped. The undated aliases
gpt-4o, gpt-4o-mini, gpt-4.1 and gpt-4.1-mini are not in OpenAI's table (only their snapshots are); they are
added as alias rows with the snapshot date, marked alias: true, so the check can say so plainly.
"""
import datetime, json, os, re, sys, urllib.request

URL = "https://developers.openai.com/api/docs/deprecations.md"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "site", "static", "assets", "model-shutdowns.js")
ALIASES = {"gpt-4o": "gpt-4o-2024-11-20", "gpt-4o-mini": "gpt-4o-mini-2024-07-18",
           "gpt-4.1": "gpt-4.1-2025-04-14", "gpt-4.1-mini": "gpt-4.1-mini-2025-04-14"}


def parse(md):
    rows = {}
    section = None
    for line in md.splitlines():
        if line.startswith("## "):
            section = line[3:].strip().lower()
            continue
        if section not in ("upcoming deprecations", "past deprecations") or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        m = re.match(r"\*\*(\w{3} \d{1,2}, \d{4})\*\*", cells[0])
        if not m or len(cells) < 3:
            continue
        date = datetime.datetime.strptime(m.group(1), "%b %d, %Y").date()
        if date.year < 2025:
            continue
        ids = re.findall(r"`([a-z0-9][a-z0-9.\-]*)`", cells[1])
        repl_cell = cells[3] if section == "upcoming deprecations" and len(cells) > 3 else cells[2]
        repl = re.findall(r"`([a-z0-9][a-z0-9.\-]*)`", repl_cell)
        for i in ids:
            if i.startswith("ft-") or i.endswith("-completions"):
                continue
            rows[i] = {"id": i, "shutdown": date.isoformat(), "replacement": " or ".join(dict.fromkeys(repl)) or "no one-to-one replacement",
                       "upcoming": section == "upcoming deprecations"}
    for alias, snap in ALIASES.items():
        if alias not in rows and snap in rows:
            rows[alias] = dict(rows[snap], id=alias, alias=True)
    return sorted(rows.values(), key=lambda r: (r["shutdown"], r["id"]))


def main():
    md = open(sys.argv[1]).read() if len(sys.argv) > 1 else urllib.request.urlopen(URL, timeout=30).read().decode()
    rows = parse(md)
    if len(rows) < 40:
        sys.exit(f"only {len(rows)} rows parsed; the page layout probably changed")
    today = datetime.date.today().isoformat()
    js = ("/* Generated by tools/gen/openai_shutdowns.py from " + URL + " on " + today + ". Do not edit by hand. */\n"
          "(function (root) { var D = { source: " + json.dumps(URL) + ", fetched: " + json.dumps(today) + ", models: " +
          json.dumps(rows, separators=(",", ":")) + " };\n"
          "  if (typeof module === 'object' && module.exports) module.exports = D; else root.PLModelShutdowns = D; })(this);\n")
    open(OUT, "w").write(js)
    print(f"{len(rows)} models ({sum(r['upcoming'] for r in rows)} upcoming) -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
